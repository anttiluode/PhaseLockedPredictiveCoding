"use strict";
/* Reproducible controlled benchmark (all 16 template frames are learned in
   advance and frozen). The unknown phase is used ONLY to generate the world,
   and by the oracle used to score errors; the hub sees only world and memory.
*/
const {bench,training,makeWorld,hub,maskCompare}=require("../core.js");
const cases=[
 {name:"global_1_tick_clean",scene:"orbit",seed:97,ticks:128,jitter:1,patchAt:[]},
 {name:"global_1_tick_local_novelty",scene:"orbit",seed:97,ticks:128,jitter:1,patchAt:[49,65,81]},
 {name:"global_2_tick_beyond_hub_radius",scene:"orbit",seed:97,ticks:128,jitter:2,patchAt:[49,65,81]},
 {name:"polar_1_tick_novelty",scene:"polar",seed:31,ticks:96,jitter:1,patchAt:[49,65]},
 {name:"two_regions_opposing_phase",scene:"orbit",seed:97,ticks:96,jitter:0,patchAt:[],kind:"split"},
];
const results={};
for(const cfg of cases){
 const run=bench(cfg),metrics={};
 for(const [mode,m] of Object.entries(run.counts)){
   metrics[mode]={reported_error_bits:m.total,false_positive_bits:m.fp,
                   captured_novelty_bits:m.tp,missed_novelty_bits:m.fn,
                   ...(mode==="hub"?{correct_phase_ticks:m.phaseCorrect}: {})};
 }
 results[cfg.name]={scenario:cfg,metrics};
 console.log(cfg.name,JSON.stringify(metrics));
}
// An observationally indistinguishable case: new scene exactly equals a
// different stored phase, even when the change is NOT generated by clock jitter.
const frame=training("orbit"),time=4,actualNovelScene=makeWorld(frame,time,+1);
const picked=hub(frame,actualNovelScene,time,0,1);
results.phase_masquerade={
 explanation:"An actual world change exactly reproducing another known phase cannot be distinguished from a clock shift using only these images.",
 fixed_phase_error_bits:maskCompare(actualNovelScene,frame[time]).error,
 selected_delta:picked.delta,
 hub_error_bits:picked.mismatch
};
console.log("phase_masquerade",JSON.stringify(results.phase_masquerade));
if(process.argv.includes("--json"))console.log(JSON.stringify(results,null,2));
